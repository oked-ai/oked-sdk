#!/usr/bin/env node
// Bundle the Claude Code plugin hook into one readable file.
//
// The file is committed. scripts/check-claude-plugin.mjs rebuilds it and
// fails if the committed copy drifted. npm run bump writes the plugin version
// and then runs this script, so a tagged release ships a matching bundle.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "plugins", "claude-code", "scripts", "oked-hook.mjs");
const MAX_BYTES = 256 * 1024;

function readVersion(path) {
  return JSON.parse(readFileSync(path, "utf8")).version;
}

const pkgVersion = readVersion(join(ROOT, "packages", "claude-code", "package.json"));
const pluginVersion = readVersion(join(ROOT, "plugins", "claude-code", ".claude-plugin", "plugin.json"));
if (pkgVersion !== pluginVersion) {
  console.error(`plugin.json version ${pluginVersion} != @oked/claude-code ${pkgVersion}`);
  process.exit(1);
}

const outfile = process.argv[2] || OUT;
await build({
  absWorkingDir: ROOT,
  entryPoints: [join(ROOT, "plugins", "claude-code", "src", "main.ts")],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node18",
  outfile,
  minify: false,
  keepNames: true,
  legalComments: "none",
  logLevel: "warning",
  alias: {
    "@oked/hook-core": join(ROOT, "packages", "hook-core", "src", "index.ts"),
    "@oked/sdk": join(ROOT, "packages", "sdk", "src", "index.ts"),
    "@oked/receipt-core": join(ROOT, "packages", "receipt-core", "src", "index.ts"),
  },
  define: {
    __OKED_PLUGIN_VERSION__: JSON.stringify(pluginVersion),
    __OKED_CLIENT_ID__: JSON.stringify(`oked-plugin@${pluginVersion}`),
  },
  banner: {
    js: [
      "#!/usr/bin/env node",
      "// Generated by scripts/build-claude-plugin.mjs. Do not edit.",
      "// Source: plugins/claude-code/src/main.ts plus packages/hook-core, packages/sdk, and packages/receipt-core.",
      `// oked-plugin@${pluginVersion}`,
      "",
    ].join("\n"),
  },
});

// Classifier comments in the SDK use an em dash. The plugin file must not.
const text = readFileSync(outfile, "utf8").replaceAll("\u2014", "-");
writeFileSync(outfile, text);
const bytes = Buffer.byteLength(text);
if (bytes > MAX_BYTES) {
  console.error(`${outfile} is ${bytes} bytes, over the ${MAX_BYTES} byte plugin file limit`);
  process.exit(1);
}
console.log(`wrote ${outfile} (${bytes} bytes, oked-plugin@${pluginVersion})`);
